from odoo import models


class PosConfig(models.Model):
    _inherit = "pos.config"

    def preview_self_order_app(self):
        self.ensure_one()
        base_url = self._get_self_order_route()
        url = f"{base_url}&studio=1"
        return {
            "type": "ir.actions.act_url",
            "url": url,
            "target": "new",
        }